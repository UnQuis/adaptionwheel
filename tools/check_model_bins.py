#!/usr/bin/env python3
"""Regenerate every shipped FRRB model from its OBJ and compare byte-for-byte.

The converter is deterministic, so a committed .bin that differs from a fresh conversion has
drifted from its source (or was made by a different converter). That mismatch is silent at
runtime: the model just loads as garbage, with no error anywhere.

Usage: python3 tools/check_model_bins.py
"""
import os
import shutil
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONVERTER = os.path.join(REPO, "tools", "gen_model_bin.py")
MODELS = os.path.join(REPO, "src", "main", "resources", "assets", "adaptionwheel", "models", "entity")
SHIPPED = ("dharma_chakra", "orbital_ring", "soe")
SCRATCH_ROOT = "/mnt/Barracuda/tmp/opencode"  # never /tmp on this machine


def main():
    os.makedirs(SCRATCH_ROOT, exist_ok=True)
    work = tempfile.mkdtemp(prefix="check-model-bins-", dir=SCRATCH_ROOT)
    failed = False
    try:
        for name in SHIPPED:
            obj = os.path.join(MODELS, name + ".obj")
            committed = os.path.join(MODELS, name + ".bin")
            generated = os.path.join(work, name + ".bin")
            if not os.path.isfile(obj) or not os.path.isfile(committed):
                failed = True
                print("FAIL %s: missing %s or %s" % (name, obj, committed), file=sys.stderr)
                continue
            try:
                subprocess.run([sys.executable, CONVERTER, obj, generated],
                               check=True, stdout=subprocess.DEVNULL)
            except subprocess.CalledProcessError:
                failed = True
                print("FAIL %s: the converter failed on %s" % (name, obj), file=sys.stderr)
                continue
            with open(committed, "rb") as a, open(generated, "rb") as b:
                want, got = a.read(), b.read()
            if want == got:
                print("OK   %s.bin (%d bytes)" % (name, len(want)))
                continue
            failed = True
            first = next((i for i, (x, y) in enumerate(zip(want, got)) if x != y),
                         min(len(want), len(got)))
            print("FAIL %s.bin: regenerated bytes differ from committed (first difference at "
                  "offset %d, %d vs %d bytes)" % (name, first, len(want), len(got)), file=sys.stderr)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if failed:
        sys.exit("one or more shipped model binaries do not match their OBJ source")
    print("All %d shipped model binaries match their OBJ source." % len(SHIPPED))


if __name__ == "__main__":
    main()
